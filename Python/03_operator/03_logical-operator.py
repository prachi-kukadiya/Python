# logical operator (and, or, not)

#and=>both condition have to be true then code will be execute

age = 20
drivinglicense = True

if age >= 18 and drivinglicense:
    print("You can drive vehicle")
else:
    print("You cannot drive vehicle")



# or =>if one condition is true then your code will be execute
driving = True
seatbelt = False

if driving==True or seatbelt==False:
    print("you can drive vehicle but its not safe")
else:
    print("you cannot drive vehicle");


